"""A small Sphinx site for a stackhands tool whose README is its manual.

    python3 branding/scaffold_docs.py NAME CHECKOUT

Writes docs/conf.py, docs/index.md (the README between its docs:start
marker and the stackhands block), a page for each of COMPAT.md and
RELEASING.md that exists, docs/requirements.txt and .github/workflows/pages.yml,
then runs sync.py for the logos, README table and navbar entry. Links in
the included part of the README must be absolute.
"""

import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

CONF = '''"""Sphinx configuration for the {name} documentation."""

project = "{name}"
author = "{name} developers"
copyright = "Copyright (c) {name} developers"

extensions = ["myst_parser", "sphinx_copybutton"]
myst_enable_extensions = ["colon_fence", "deflist"]
myst_heading_anchors = 3
exclude_patterns = ["_build"]

html_theme = "shibuya"
html_title = "{name}"
html_static_path = ["_static"]
html_favicon = "_static/favicon.svg"
html_baseurl = "{docs}"
html_theme_options = {{
    "github_url": "{repo}",
    "accent_color": "teal",
    "dark_code": True,
    "light_logo": "_static/logo-light.svg",
    "dark_logo": "_static/logo-dark.svg",
    "nav_links": [
        # stackhands:begin
        # stackhands:end
    ],
}}
html_context = {{
    "source_type": "github",
    "source_user": "stackhands",
    "source_repo": "{name}",
    "source_version": "main",
    "source_docs_path": "/docs/",
}}
'''

INDEX = '''# {name}

```{{image}} _static/logo-light.svg
:alt: {name}
:width: 420px
:class: only-light
```

```{{image}} _static/logo-dark.svg
:alt: {name}
:width: 420px
:class: only-dark
```

```{{include}} ../README.md
:start-after: <!-- docs:start -->
:end-before: <!-- stackhands:begin -->
```

```{{toctree}}
:hidden:
:maxdepth: 1

{pages}
```
{more}
'''

PAGES_YML = '''name: pages
# Build the documentation with warnings as errors; on main, publish it to
# {docs}
on:
  push:
    branches: [main]
  pull_request:
permissions:
  contents: read
concurrency:
  group: pages-${{{{ github.ref }}}}
  cancel-in-progress: true
jobs:
  build:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-python@v5
        with:
          python-version: "3.12"
      - run: python -m pip install -r docs/requirements.txt
      - run: python -m sphinx -W -b html docs docs/_build/html
{extra}      - uses: actions/upload-pages-artifact@v3
        if: github.event_name == 'push' && github.ref == 'refs/heads/main'
        with:
          path: docs/_build/html
  deploy:
    if: github.event_name == 'push' && github.ref == 'refs/heads/main'
    needs: build
    runs-on: ubuntu-latest
    permissions:
      pages: write
      id-token: write
    environment:
      name: github-pages
      url: ${{{{ steps.deployment.outputs.page_url }}}}
    steps:
      - id: deployment
        uses: actions/deploy-pages@v4
'''

ZIG_DOCS = '''      - uses: mlugg/setup-zig@v2
        with:
          version: 0.17.1
      - run: zig build docs --prefix zig-out && cp -r zig-out/docs docs/_build/html/api
'''

REQUIREMENTS = """Sphinx==8.2.3
myst-parser==5.1.0
shibuya==2025.12.13
sphinx-copybutton==0.5.2
"""


def tool(name):
    with open(os.path.join(HERE, "ecosystem.json")) as handle:
        return next(t for t in json.load(handle) if t["name"] == name)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as handle:
        handle.write(text)


def main(name, checkout):
    t = tool(name)
    docs = os.path.join(checkout, "docs")
    pages = []
    for src, page, title in (("COMPAT.md", "compat", "Compatibility"), ("RELEASING.md", "releasing", "Releasing")):
        if os.path.exists(os.path.join(checkout, src)):
            write(os.path.join(docs, page + ".md"), f"```{{include}} ../{src}\n```\n")
            pages.append(page)
    zig_api = name == "zig-common"
    more = ("\nThe Zig API reference, generated by `zig build docs` from the doc comments, is at "
            f"[api/]({t['docs']}api/).\n") if zig_api else ""
    write(os.path.join(docs, "conf.py"), CONF.format(name=name, docs=t["docs"], repo=t["repo"]))
    write(os.path.join(docs, "index.md"), INDEX.format(name=name, pages="\n".join(pages), more=more))
    write(os.path.join(docs, "requirements.txt"), REQUIREMENTS)
    write(os.path.join(checkout, ".github", "workflows", "pages.yml"),
          PAGES_YML.format(docs=t["docs"], extra=ZIG_DOCS if zig_api else ""))
    subprocess.run([sys.executable, os.path.join(HERE, "sync.py"), name, checkout, "--static", "docs/_static"], check=True)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
