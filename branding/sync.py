"""Write the shared stackhands branding into one tool's checkout.

    python3 branding/sync.py NAME CHECKOUT [--static DIR]

- branding/logo/: mark, dark mark, light and dark wordmarks, favicon;
- DIR (a docs static directory, relative to CHECKOUT), if given: the same files;
- README.md: the block between the stackhands markers, a table of every tool
  with its docs and repository, the tool itself marked;
- every *.md under docs/ that holds the README markers: the same table;
- every *.py under docs/ that holds the ecosystem markers: the Shibuya
  "stackhands" navbar entry listing the other tools.

ecosystem.json is the one list of tools, links and jobs.
"""

import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import logos  # noqa: E402

BEGIN, END = "<!-- stackhands:begin -->", "<!-- stackhands:end -->"
PY_BEGIN, PY_END = "# stackhands:begin", "# stackhands:end"


def tools():
    with open(os.path.join(HERE, "ecosystem.json")) as handle:
        return json.load(handle)


def readme_block(name):
    rows = []
    for t in tools():
        label = f"**{t['name']}**" if t["name"] == name else f"[{t['name']}]({t['repo']})"
        rows.append(f"| {label} | {t['job']} | [docs]({t['docs']}) |")
    return "\n".join([
        BEGIN,
        "## Part of stackhands",
        "",
        f"{name} is one of the [stackhands](https://github.com/stackhands) tools for building, installing "
        "and maintaining an HPC software stack with EasyBuild on top of EESSI.",
        "",
        "| Tool | Job | Docs |",
        "|---|---|---|",
        *rows,
        END,
    ])


def nav_block(name, indent):
    pad = " " * indent
    lines = [f"{pad}{PY_BEGIN} (generated by stackhands/.github branding/sync.py)",
             f"{pad}{{", f'{pad}    "title": "stackhands",', f'{pad}    "children": [']
    for t in tools():
        if t["name"] == name:
            continue
        lines += [f"{pad}        {{", f'{pad}            "title": "{t["name"]}",', f'{pad}            "url": "{t["docs"]}",',
                  f'{pad}            "summary": "{t["job"]}",', f"{pad}        }},"]
    lines += [f"{pad}    ],", f"{pad}}},", f"{pad}{PY_END}"]
    return "\n".join(lines)


def write_logos(name, dest):
    os.makedirs(dest, exist_ok=True)
    glyph, desc = logos.TOOLS[name]
    files = {
        "mark.svg": logos.mark(name, glyph, desc, logos.LIGHT, logos.LIGHT["tile"]),
        "mark-dark.svg": logos.mark(name, glyph, desc, logos.DARK, logos.DARK["tile"]),
        "logo-light.svg": logos.wordmark(name, glyph, desc, logos.LIGHT, "light"),
        "logo-dark.svg": logos.wordmark(name, glyph, desc, logos.DARK, "dark"),
        "favicon.svg": logos.favicon(name, glyph, logos.LIGHT),
    }
    for fname, text in files.items():
        with open(os.path.join(dest, fname), "w") as handle:
            handle.write(text)


def replace_between(text, begin, end, block):
    pattern = re.compile(r"^[ \t]*" + re.escape(begin) + r".*?" + re.escape(end) + r"[^\n]*", re.S | re.M)
    if not pattern.search(text):
        return None
    return pattern.sub(lambda _m: block, text, count=1)


def main(argv):
    name, checkout = argv[0], argv[1]
    static = argv[argv.index("--static") + 1] if "--static" in argv else None
    if name in logos.TOOLS:
        write_logos(name, os.path.join(checkout, "branding", "logo"))
        if static:
            write_logos(name, os.path.join(checkout, static))
    readme = os.path.join(checkout, "README.md")
    text = open(readme).read()
    new = replace_between(text, BEGIN, END, readme_block(name))
    if new is None:
        new = text.rstrip("\n") + "\n\n" + readme_block(name) + "\n"
    with open(readme, "w") as handle:
        handle.write(new)
    for root, _dirs, files in os.walk(os.path.join(checkout, "docs")):
        for f in files:
            path = os.path.join(root, f)
            if f.endswith(".md"):
                text = open(path).read()
                new = replace_between(text, BEGIN, END, readme_block(name))
                if new is not None and new != text:
                    with open(path, "w") as handle:
                        handle.write(new)
                continue
            if not f.endswith(".py"):
                continue
            path = os.path.join(root, f)
            text = open(path).read()
            found = re.search(r"^([ \t]*)" + re.escape(PY_BEGIN), text, re.M)
            if not found:
                continue
            with open(path, "w") as handle:
                handle.write(replace_between(text, PY_BEGIN, PY_END, nav_block(name, len(found.group(1)))))


if __name__ == "__main__":
    main(sys.argv[1:])
